function m(
  id: string,
  category: MealCategory,
  image: string,
  name: [string, string],
  desc: [string, string],
  calories: number,
  ing: [string, string][],
  allergens: string[],
  diet: string[],
  spice: 0 | 1 | 2 | 3,
  day: number,
): Meal {
  const protein = Math.round((calories * 0.28) / 4);
  const carbs = Math.round((calories * 0.45) / 4);
  const fat = Math.round((calories * 0.27) / 9);
  return {
    id,
    category,
    image,
    name: { fr: name[0], en: name[1] },
    description: { fr: desc[0], en: desc[1] },
    calories,
    nutrition: { calories, protein, carbs, fat },
    ingredients: ing.map(([fr, en]) => ({ fr, en })),
    allergens,
    diet,
    spice,
    date: iso(currentWeek()[day]),
  };
}

